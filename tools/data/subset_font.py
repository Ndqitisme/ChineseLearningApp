"""Subsets the bundled fonts to the characters the app uses, renamed "TieuMai Kai" (LXGW WenKai is an OFL Reserved Font Name).
HSK 4-6-only glyphs go to TieuMaiKai-ext.woff2, whose unicode-range in src/lib/ui/base.css is rewritten here so it loads only when needed.
Usage: .cache/venv/Scripts/python tools/data/subset_font.py  (needs: pip install fonttools brotli)
"""
import pathlib
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / ".cache" / "sources"
OUT = ROOT / "public" / "fonts"
BASE_CSS = ROOT / "src" / "lib" / "ui" / "base.css"
EXT_START = "/* tieumai-ext: generated by tools/data/subset_font.py */"
EXT_END = "/* /tieumai-ext */"

LATIN = "".join(chr(c) for c in range(0x20, 0x7F))
VIETNAMESE = "ÀÁÂÃÈÉÊÌÍÒÓÔÕÙÚÝàáâãèéêìíòóôõùúýĂăĐđĨĩŨũƠơƯư" + "".join(chr(c) for c in range(0x1EA0, 0x1EFA))
PINYIN = "āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜüÜĀÁǍÀĒÉĚÈĪÍǏÌŌÓǑÒŪÚǓÙǕǗǙǛ"
PUNCT = "，。！？、：；“”‘’（）《》〈〉【】…—～·「」『』·•–—’‘“”…×÷°%"


def subset_font(src: pathlib.Path, dst: pathlib.Path, text: str, family: str | None) -> None:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.notdef_outline = True
    font = TTFont(src)
    sub = subset.Subsetter(options)
    sub.populate(text=text)
    sub.subset(font)
    if family:
        rename(font, family)
    dst.parent.mkdir(parents=True, exist_ok=True)
    font.flavor = "woff2"
    font.save(dst)
    print(f"{dst.relative_to(ROOT)}: {dst.stat().st_size // 1024} KB")


def rename(font: TTFont, family: str) -> None:
    ps_name = family.replace(" ", "") + "-Regular"
    names = {1: family, 2: "Regular", 3: f"{ps_name};subset", 4: f"{family} Regular", 6: ps_name, 16: family, 17: "Regular"}
    table = font["name"]
    for record in list(table.names):
        if record.nameID in names:
            table.setName(names[record.nameID], record.nameID, record.platformID, record.platEncID, record.langID)
    for record in list(table.names):
        if record.nameID in (21, 22):  # WWS names would still carry the reserved name
            table.removeNames(nameID=record.nameID)


def unicode_range(chars: str) -> str:
    points = sorted({ord(c) for c in chars})
    ranges: list[list[int]] = []
    for p in points:
        if ranges and p == ranges[-1][1] + 1:
            ranges[-1][1] = p
        else:
            ranges.append([p, p])
    return ", ".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)


def write_ext_face(chars: str) -> None:
    """Rewrites the extension @font-face between the markers in base.css (declared after the core face)."""
    face = (f"{EXT_START}\n@font-face {{\n  font-family: 'TieuMai Kai';\n"
            f"  src: url('/fonts/TieuMaiKai-ext.woff2') format('woff2');\n  font-display: block;\n"
            f"  unicode-range: {unicode_range(chars)};\n}}\n{EXT_END}")
    css = BASE_CSS.read_text(encoding="utf-8")
    start, end = css.find(EXT_START), css.find(EXT_END)
    if start < 0 or end < 0:
        raise SystemExit(f"{BASE_CSS.relative_to(ROOT)}: markers {EXT_START!r} / {EXT_END!r} not found")
    BASE_CSS.write_text(css[:start] + face + css[end + len(EXT_END):], encoding="utf-8", newline="\n")
    print(f"{BASE_CSS.relative_to(ROOT)}: unicode-range for {len(set(chars))} characters")


def main() -> int:
    charset_file = ROOT / ".cache" / "charset.txt"
    if not charset_file.exists():
        print("run `pnpm data:build` first (it writes .cache/charset.txt)", file=sys.stderr)
        return 1
    han = charset_file.read_text(encoding="utf-8")
    ui_han = "小梅学习中文汉字拼音今天复习写声调练习词"  # Chinese used in UI chrome
    core = han + ui_han
    ext = "".join(c for c in (ROOT / ".cache" / "charset-ext.txt").read_text(encoding="utf-8") if c not in core)
    subset_font(SRC / "LXGWWenKaiLite-Regular.ttf", OUT / "TieuMaiKai.woff2",
                core + LATIN + PINYIN + VIETNAMESE + PUNCT, "TieuMai Kai")
    subset_font(SRC / "LXGWWenKaiLite-Regular.ttf", OUT / "TieuMaiKai-ext.woff2", ext, "TieuMai Kai")
    write_ext_face(ext)
    subset_font(SRC / "Nunito.ttf", OUT / "Nunito.woff2", LATIN + VIETNAMESE + PUNCT + "←→↑↓✓✗★☆♥", None)
    licenses = ROOT / "public" / "licenses"
    licenses.mkdir(parents=True, exist_ok=True)
    (licenses / "OFL-TieuMaiKai.txt").write_bytes((SRC / "OFL-LXGWWenKai.txt").read_bytes())
    (licenses / "OFL-Nunito.txt").write_bytes((SRC / "OFL-Nunito.txt").read_bytes())
    return 0


if __name__ == "__main__":
    sys.exit(main())
